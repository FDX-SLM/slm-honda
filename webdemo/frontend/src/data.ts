// --- L1 triage fallback: classify complaint → template (cue-based) ---
export interface TriageResult {
  layer: Layer;
  rc: string;
  rb: string;
  sev: "2" | "3";
  conf: number;
  cues: string[];
  templateIdx: number;
}

export function triage(complaint: string): TriageResult {
  const s = complaint.toLowerCase();
  const has = (arr: string[]) => arr.filter((w) => s.includes(w));

  const eligCues = has(["subscribe", "touring", "paid", "already pay", "prompt", "entitlement"]);
  const cacheCues = has(["website", "web", "app", "flicker", "logging out", "on and off", "cache"]);
  const tcuCues = has(["garage", "timeout", "times out", "signal", "no signal", "underground", "parked"]);

  const score = [
    { idx: 0, cues: eligCues },
    { idx: 1, cues: cacheCues },
    { idx: 2, cues: tcuCues },
  ].sort((a, b) => b.cues.length - a.cues.length)[0];

  const idx = score.cues.length ? score.idx : 0; // fallback ELIG
  const t = TEMPLATES[idx];
  return {
    layer: t.layer,
    rc: t.rc,
    rb: t.rb,
    sev: t.sev,
    conf: t.conf,
    cues: score.cues.length ? score.cues : ["(fuzzy match — most likely root cause)"],
    templateIdx: idx,
  };
}

