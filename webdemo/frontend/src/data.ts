// Mock data for the Honda AMS web demo — SLM Resolver (L1 triage → L2/L3 renovation).
// Everything here is mock/hard-coded so the demo flow runs smoothly; swap in the real SLM later.
// RFP PM2.0 mapping: L2 = fix by operation (Common L2 Services, p.78-79);
// L3 = code fix / renovation (Common L3 Services p.80 + Zero Dev p.84).

export type Layer = "l2" | "l3" | "route";

export interface Customer {
  ini: string;
  name: string;
  loc: string;
  email: string;
  phone: string;
  veh: string; // may contain <b>
  vin: string; // may contain <b class='ok'>
}

export interface Step {
  k: string;
  kk: string;
  v: string; // allows <span class='hl|cy'>
  ev?: string[]; // evidence, allows <span class='g|r|a|c|f'>
  real?: boolean; // evidence generated by the real SLM (SLM badge)
}

/** RCA generated by the SLM at L1 (real) — carried into the resolver for display. */
export interface SlmRca {
  evidence: string[];
  summary: string;
  nextActions: string[];
  owner?: string | null;
  escalation?: string | null;
  affectedSystem?: string | null;
  similarIncident?: string | null;
  missing?: string[];
}

export interface DiffLine {
  t: "cmt" | "add" | "del";
  x: string;
}
export interface ExecLine {
  t: "cmd" | "out" | "ok";
  x: string;
}
export interface RouteInfo {
  rc: string;
  to: string; // allows <b>
  chips: { t: string; ok?: boolean }[];
}

export type Status = "queued" | "processing" | "resolved";

export interface Ticket {
  id: string;
  sev: "2" | "3";
  sys: string;
  impact: string;
  title: string;
  complaint: string;
  customer: Customer;
  layer: Layer;
  rc: string;
  rb: string;
  conf: number;
  mttr: string;
  steps: Step[];
  diff?: DiffLine[];
  testName?: string;
  reEval?: string;
  exec?: ExecLine[];
  route?: RouteInfo;
  slm?: SlmRca; // real RCA (if the ticket came from L1 via the SLM)
  status: Status;
}

