// --- map root cause (returned by the SLM) → resolver template + layer ---
export const ABSTAIN_RC = "INSUFFICIENT_EVIDENCE";
export const RC_TO_IDX: Record<string, number> = {
  ELIGIBILITY_RULE_CONFLICT: 0,
  ENTITLEMENT_CACHE_STALE: 1,
  TCU_OFFLINE: 2,
  PAYMENT_WEBHOOK_LOST: 3,
  TOKEN_SCOPE: 4,
};
export function idxForRc(rc: string): number {
  return RC_TO_IDX[rc] ?? 0;
}
export function rcToLayer(rc: string): Layer {
  return TEMPLATES[idxForRc(rc)].layer;
}
export function sevForRc(rc: string): "2" | "3" {
  return TEMPLATES[idxForRc(rc)].sev;
}
export function defaultCustomer(rc: string): Customer {
  return TEMPLATES[idxForRc(rc)].customer;
}

const esc = (s: string) =>
  s.replace(/[&<>]/g, (c) => (({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }) as Record<string, string>)[c]);

/** Build the L2/L3 ticket from the SLM result at L1.
 * - rc / conf / runbook: REAL from the SLM.
 * - RCA (evidence, why, fix_steps, owner…): REAL from the SLM → injected into the Investigate step + RCA card.
 * - Renovation (diff / exec / route): still from the template (mock) until #2-#4 are made real.
 * `d` is the NormalizedDiagnosis returned by /api/diagnose/slm. */
export function ticketFromSLM(id: string, customer: Customer, complaint: string, d: any): Ticket {
  const rc: string = d.rootCause || "ELIGIBILITY_RULE_CONFLICT";
  const conf: number = typeof d.confidence === "number" ? d.confidence : 0;
  const base = TEMPLATES[idxForRc(rc)];
  const evidence: string[] = Array.isArray(d.evidence) ? d.evidence : [];

  const steps: Step[] = base.steps.map((s) => ({ ...s, ev: s.ev ? [...s.ev] : undefined }));
  const handoff = `<span class='f'>L1 handoff · SLM:</span> ${rc} · conf ${conf.toFixed(2)}`;
  steps[0] = { ...steps[0], ev: [handoff, ...(steps[0].ev || [])] };
  // Investigate: replace the canned evidence with the REAL SLM evidence (cue-grounded quotes).
  if (evidence.length) {
    steps[1] = {
      ...steps[1],
      real: true,
      ev: evidence.map((e) => `<span class='g'>“</span>${esc(e)}<span class='g'>”</span>`),
    };
  }

  const slm: SlmRca = {
    evidence,
    summary: d.summary || "",
    nextActions: Array.isArray(d.nextActions) ? d.nextActions : [],
    owner: d.owner || null,
    escalation: d.escalation || null,
    affectedSystem: d.affectedSystem || null,
    similarIncident: d.similarIncident || null,
    missing: Array.isArray(d.missingEvidence) ? d.missingEvidence : [],
  };

  return { ...base, id, customer, complaint, rc, conf, rb: d.runbook || base.rb, steps, slm, status: "queued" };
}

export function layerBadge(layer: Layer): { label: string; cls: string } {
  if (layer === "l3") return { label: "L3 · code fix", cls: "l3" };
  if (layer === "l2") return { label: "L2 · auto-exec", cls: "l2" };
  return { label: "Route · no-code", cls: "route" };
}
